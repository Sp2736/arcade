#!/usr/bin/env python3
"""
archive_stats.py — refreshes <!--ARCHIVE_STATS_START-->…<!--ARCHIVE_STATS_END-->
in README.md with polished, snapshot-style stats for a completed/mature repo.

Environment variables:
  GH_TOKEN   — PAT or GITHUB_TOKEN
  GH_REPO    — "owner/repo"
"""
import os, json, re, datetime as dt, urllib.request, urllib.error
from pathlib import Path

TOKEN = os.environ.get("GH_TOKEN", "")
REPO  = os.environ.get("GH_REPO", "")
ROOT  = Path(__file__).resolve().parent.parent
IST   = dt.timezone(dt.timedelta(hours=5, minutes=30))

def api(path):
    url = f"https://api.github.com/repos/{REPO}/{path}"
    h = {"User-Agent": "archive-stats", "Accept": "application/vnd.github+json"}
    if TOKEN:
        h["Authorization"] = f"Bearer {TOKEN}"
    with urllib.request.urlopen(urllib.request.Request(url, headers=h), timeout=20) as r:
        return json.load(r), dict(r.headers)

def api_data(path):
    data, _ = api(path)
    return data

def total_commits():
    """Count total commits via Link header pagination trick."""
    url = f"https://api.github.com/repos/{REPO}/commits?per_page=1"
    h = {"User-Agent": "archive-stats", "Accept": "application/vnd.github+json"}
    if TOKEN:
        h["Authorization"] = f"Bearer {TOKEN}"
    with urllib.request.urlopen(urllib.request.Request(url, headers=h), timeout=20) as r:
        link = r.headers.get("Link", "")
        _ = r.read()
    # parse last page number
    for part in link.split(","):
        if 'rel="last"' in part:
            m = re.search(r'[?&]page=(\d+)', part)
            if m:
                return int(m.group(1))
    return 1  # only one commit

def latest_release():
    try:
        rel = api_data("releases/latest")
        return rel.get("tag_name", "N/A"), rel.get("html_url", ""), rel.get("published_at", "")[:10]
    except Exception:
        return "N/A", "", ""

def top_contributors(n=5):
    try:
        contribs = api_data(f"contributors?per_page={n}")
        return [(c["login"], c["contributions"], c["html_url"]) for c in contribs[:n]]
    except Exception:
        return []

def gh_pages_date():
    try:
        b = api_data("branches/gh-pages")
        return b["commit"]["commit"]["committer"]["date"][:10]
    except Exception:
        return None

def build_block():
    now    = dt.datetime.now(IST).strftime("%d %b %Y, %I:%M %p IST")
    meta   = api_data("")
    owner, name = REPO.split("/", 1)

    stars    = meta.get("stargazers_count", 0)
    forks    = meta.get("forks_count", 0)
    watchers = meta.get("watchers_count", 0)
    size_kb  = meta.get("size", 0)
    created  = meta.get("created_at", "")[:10]
    pushed   = meta.get("pushed_at", "")[:10]
    license_ = (meta.get("license") or {}).get("spdx_id", "None")
    desc     = meta.get("description") or ""
    homepage = meta.get("homepage") or ""
    topics   = meta.get("topics", [])

    total_c  = total_commits()
    tag, rel_url, rel_date = latest_release()
    deploy   = gh_pages_date()

    # languages
    try:
        lang_data = api_data("languages")
        total_b   = sum(lang_data.values()) or 1
        langs     = [(l, round(100 * s / total_b, 1))
                     for l, s in sorted(lang_data.items(), key=lambda kv: -kv[1])[:6]]
    except Exception:
        langs = []

    # contributors
    contribs = top_contributors(5)

    lines = [
        f"<!-- auto-generated by archive_stats.py — do not edit this block manually -->",
        f"",
        f"### 📦 Project Snapshot &nbsp;·&nbsp; <sub>refreshed {now}</sub>",
        f"",
        # badge row (Shields.io — no token needed, public data)
        f"![Stars](https://img.shields.io/github/stars/{REPO}?style=flat-square&color=58a6ff)"
        f" ![Forks](https://img.shields.io/github/forks/{REPO}?style=flat-square&color=58a6ff)"
        f" ![Last Commit](https://img.shields.io/github/last-commit/{REPO}?style=flat-square&color=58a6ff)"
        f" ![License](https://img.shields.io/github/license/{REPO}?style=flat-square&color=58a6ff)",
        f"",
        f"| 📅 Created | 🔄 Last Push | 💬 Total Commits | ⭐ Stars | 🍴 Forks | 📜 License |",
        f"|---|---|---|---|---|---|",
        f"| {created} | {pushed} | {total_c:,} | {stars} | {forks} | {license_} |",
        f"",
    ]

    if tag != "N/A":
        lines += [
            f"**Latest Release:** [{tag}]({rel_url}) &nbsp; `{rel_date}`",
            f"",
        ]

    if deploy:
        lines += [
            f"**Live Demo:** [sp2736.github.io/{name}](https://sp2736.github.io/{name})"
            f" &nbsp; <sub>last deployed {deploy}</sub>",
            f"",
        ]
    elif homepage:
        lines += [
            f"**Live:** [{homepage}]({homepage})",
            f"",
        ]

    if langs:
        bar = "  ".join(f"`{l}` {p}%" for l, p in langs)
        lines += [f"**Languages:** {bar}", f""]

    if topics:
        tag_badges = " ".join(f"`{t}`" for t in topics[:10])
        lines += [f"**Topics:** {tag_badges}", f""]

    if contribs:
        contrib_md = " · ".join(
            f"[@{login}](https://github.com/{login}) `{n}`" for login, n, _ in contribs
        )
        lines += [f"**Top Contributors:** {contrib_md}", f""]

    return "\n".join(lines)

def patch_readme(block):
    readme = ROOT / "README.md"
    text   = readme.read_text(encoding="utf-8")

    start_tag = "<!--ARCHIVE_STATS_START-->"
    end_tag   = "<!--ARCHIVE_STATS_END-->"

    if start_tag not in text:
        text += f"\n\n---\n\n{start_tag}\n{block}\n{end_tag}\n"
    else:
        pat  = re.compile(rf"{re.escape(start_tag)}.*?{re.escape(end_tag)}", re.S)
        text = pat.sub(f"{start_tag}\n{block}\n{end_tag}", text)

    readme.write_text(text, encoding="utf-8")
    print("README patched.")

if __name__ == "__main__":
    patch_readme(build_block())
